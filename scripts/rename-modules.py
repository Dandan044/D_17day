def main() -> None:
    write = '--write' in sys.argv
    blobs: dict[Path, bytes] = {}
    for rel in TARGETS:
        p = ROOT / rel
        if not p.exists():
            sys.exit(f'目标文件不存在: {rel}')
        blobs[p] = p.read_bytes()

    hits: dict[str, int] = {old: 0 for old, _ in MAP}
    per_file: dict[str, int] = {rel: 0 for rel in TARGETS}

    for p, raw in blobs.items():
        rel = str(p.relative_to(ROOT)).replace('\\', '/')
        for old, new in MAP:
            b_old, b_new = old.encode('utf-8'), new.encode('utf-8')
            n = raw.count(b_old)
            if n:
                raw = raw.replace(b_old, b_new)
                hits[old] += n
                per_file[rel] += n
        blobs[p] = raw

    total = sum(hits.values())
    print(f'{"写入" if write else "干跑"}：共 {total} 处替换\n')
    for rel, n in per_file.items():
        if n:
            print(f'  {n:3d}  {rel}')

    missed = [old for old, n in hits.items() if n == 0]
    if missed:
        print('\n以下映射一处也没命中（可能拼错或已改过，请核对）：')
        for old in missed:
            print(f'  · {old}')
    else:
        print('\n映射表全部命中。')

    if write:
        for p, raw in blobs.items():
            p.write_bytes(raw)
        print('\n已写回。')


if __name__ == '__main__':
    main()
